#!/usr/bin/env python3
"""Render the `## Contents` section of every long skill document.

Why these documents carry one. A skill's `SKILL.md` and the files beside it are
read from disk on demand, and a reader that is unsure how much it needs
previews rather than reads — `head -100`, a ranged read — so a document longer
than that can be consumed in part with no signal that the rest exists. A
Contents section at the first section boundary puts the whole scope inside the
part that always gets read. Anthropic's skill-authoring guidance sets the
threshold at 100 lines; `LONG_ENOUGH` is that number.

Why it is rendered rather than written. A hand-typed Contents is a second copy
of the document's own heading list — a drift surface in the sense
`.claude/rules/no-drift-surfaces.md` gives the term, and one that rots on the
next section rename with nothing to notice. Here the headings are the owner and
the section is derived from them, so the copy cannot diverge:
`render_reference_toc.py check` re-derives every one and fails on any
difference.

The section lists `##` headings only. Deeper ones are the body of a section a
reader has already been pointed at, and listing them would make the Contents
compete with the document for the budget it exists to protect.

    python3 scripts/render_reference_toc.py write   # rewrite in place
    python3 scripts/render_reference_toc.py check   # CI gate; exit 1 on any diff

`write` skips a document whose first line declares it generated in full — its
own renderer owns every byte, including the Contents section. `check` does not
skip it: the obligation is the document's, whoever writes it.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
PLUGINS_ROOT = REPO_ROOT / "plugins"

# Anthropic's skill-authoring guidance: reference files longer than this get a
# table of contents, so a partial read still shows the full scope.
LONG_ENOUGH = 100

# A Contents section is only worth its tokens once a document has sections to
# choose between; one heading is not a choice.
FEWEST_SECTIONS = 2

TOC_HEADING = "## Contents"

_FENCE_RE = re.compile(r"^(```|~~~)")
_H2_RE = re.compile(r"^## +(?P<title>\S.*?)\s*$")
_GENERATED_IN_FULL_RE = re.compile(r"^<!--\s*GENERATED by ")


def documents() -> list[Path]:
    """Every skill document long enough to need a Contents section.

    Skill trees only. An agent definition is loaded whole as a system prompt
    rather than previewed, so a Contents section there would be cost with no
    reader; a README is for a person browsing the repository.
    """
    return sorted(
        p for p in PLUGINS_ROOT.glob("*/skills/**/*.md")
        if len(p.read_text(encoding="utf-8").splitlines()) > LONG_ENOUGH
    )


def _lines_outside_fences(text: str):
    """Yield (index, line) for lines that are not inside a fenced block.

    A `## ` inside a fence is sample output or a shell comment, not a section
    of this document.
    """
    fence: str | None = None
    for i, line in enumerate(text.splitlines()):
        marker = _FENCE_RE.match(line)
        if marker:
            if fence is None:
                fence = marker.group(1)
            elif line.startswith(fence):
                fence = None
            continue
        if fence is None:
            yield i, line


def headings(text: str) -> list[str]:
    """The document's `##` section titles, in order, excluding Contents."""
    found = []
    for _, line in _lines_outside_fences(text):
        match = _H2_RE.match(line)
        if match and line.rstrip() != TOC_HEADING:
            found.append(match.group("title"))
    return found


def _section_bounds(text: str) -> tuple[int, int] | None:
    """Line range of the existing Contents section, or None.

    Ends at the next `##` heading, so a Contents section that has fallen out of
    date is replaced rather than appended to.
    """
    start = None
    for i, line in _lines_outside_fences(text):
        if line.rstrip() == TOC_HEADING:
            start = i
            continue
        if start is not None and _H2_RE.match(line):
            return start, i
    return (start, len(text.splitlines())) if start is not None else None


def _first_section_line(text: str) -> int | None:
    """Line index of the first `##` heading that is not Contents."""
    for i, line in _lines_outside_fences(text):
        if _H2_RE.match(line) and line.rstrip() != TOC_HEADING:
            return i
    return None


def render_text(text: str) -> str:
    """The document with its Contents section derived from its own headings.

    Placed directly above the first section rather than under the title: the
    prose between them says what the document is for, which is what a reader
    deciding whether to read on needs first.
    """
    titles = headings(text)
    lines = text.splitlines()

    existing = _section_bounds(text)
    if existing:
        start, end = existing
        lines = lines[:start] + lines[end:]
        text = "\n".join(lines) + ("\n" if text.endswith("\n") else "")
        # Trailing blank lines left where the old section stood.
        while start < len(lines) and not lines[start].strip():
            lines.pop(start)

    if len(titles) < FEWEST_SECTIONS:
        return "\n".join(lines) + ("\n" if text.endswith("\n") else "")

    at = _first_section_line("\n".join(lines))
    if at is None:  # unreachable while titles is non-empty; fail loud if not
        raise SystemExit(f"no section to place Contents above, yet {len(titles)} headings parsed")

    block = [TOC_HEADING, ""] + [f"- {t}" for t in titles] + [""]
    return "\n".join(lines[:at] + block + lines[at:]) + "\n"


def main(argv: list[str]) -> int:
    if len(argv) != 2 or argv[1] not in {"write", "check"}:
        print(__doc__.splitlines()[0])
        print("usage: render_reference_toc.py {write|check}")
        return 2
    mode = argv[1]

    targets = documents()
    if not targets:
        raise SystemExit(
            f"no skill document exceeds {LONG_ENOUGH} lines — the scan found nothing "
            "to grade, which means it has stopped measuring rather than passing")

    stale: list[str] = []
    written = 0
    for path in targets:
        current = path.read_text(encoding="utf-8")
        wanted = render_text(current)
        if wanted == current:
            continue
        generated_in_full = bool(_GENERATED_IN_FULL_RE.match(current))
        if mode == "check" or generated_in_full:
            hint = " (generated in full; fix its renderer)" if generated_in_full else ""
            stale.append(f"{path.relative_to(REPO_ROOT).as_posix()}{hint}")
            continue
        path.write_text(wanted, encoding="utf-8")
        written += 1

    if stale:
        print("Contents section stale or missing:", file=sys.stderr)
        for name in stale:
            print(f"  {name}", file=sys.stderr)
        print("\nRun: python3 scripts/render_reference_toc.py write", file=sys.stderr)
        return 1

    graded = len(targets)
    print(f"{graded} long skill document(s) carry a Contents section derived from their headings"
          + (f"; {written} rewritten" if written else ""))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
