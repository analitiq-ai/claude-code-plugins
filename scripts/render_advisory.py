#!/usr/bin/env python3
"""Render the rules the plugin authors against, tier by tier.

The rules live in the pinned `analitiq-contract-models` package as one registry
(`analitiq.contracts.shared.advisory.all_rules()`): each carries a stable
`ADV-*` id, the resource it constrains, a one-line normative statement, and its
tier — what enforces it, or the declared reason nothing does. That registry is
the single source of truth; this script only *renders* it, so agents have an
offline-readable file to cite instead of hand-restating rules in prose.

The three tiers render differently because an agent needs different things from
each: a relational failure arrives with the id already in the message, a
structural one names the field and nothing else, and a waived rule will never
arrive at all. The structural table's member lists are read off the **live
models** rather than typed here — the point of that tier is to end the copy, so
the renderer must not become one.

The generated file is a **pinned copy**, not a second source: `tests/connector_builder`
regenerates it and fails when it is stale, so a contract change surfaces as a red
build rather than silent prose drift.

Usage:
    render_advisory.py write    # regenerate the markdown file in place
    render_advisory.py check    # exit 1 if the file is stale (CI)
"""

from __future__ import annotations

import os
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent

# This repo is the contract's SOURCE, so bootstrap the same way render_schemas.py
# does rather than relying on an installed wheel — requirements-dev.txt
# deliberately does not install one. Keeps the script runnable standalone (CI
# calls it directly, outside pytest and its conftest).
sys.path.insert(0, str(REPO_ROOT / "packages" / "contract-models" / "src"))
# `analitiq.contracts.shared.common` reads os.environ["DOMAIN"] at import and
# raises KeyError without it.
os.environ.setdefault("DOMAIN", "analitiq.ai")
OUTPUT_PATH = (
    REPO_ROOT / "plugins" / "analitiq-connector-builder" / "skills" / "connector-builder" / "references" / "advisory-rules.md"
)

# Only the resources this plugin authors. Pipelines, streams, connection
# documents, and database endpoints are owned elsewhere (database endpoints are
# produced by the connector's `resource_discovery` at runtime, never authored
# here), so their rules are noise in an authoring reference.
PLUGIN_RESOURCES = ("connector", "connector-package", "api-endpoint", "type-map", "shared")

# Rules on documents this plugin does NOT author but authors *against* — the
# database endpoint its `resource_discovery` produces at runtime, the stream
# that will reference its endpoints. Prose here cites them to say where a
# boundary is ("never author one of these"), and a citation an agent cannot
# resolve teaches nothing, so they are rendered — in their own section, framed
# as somebody else's rules.
#
# Named one by one rather than by resource: admitting a whole foreign resource
# is what `test_reference_covers_only_authored_resources` exists to prevent,
# and every id here had to be argued for at a prose site.
BORROWED_RULE_IDS = (
    "ADV-DBEP-005",
    "ADV-DBEP-006",
    "ADV-DBEP-007",
    "ADV-STRM-003",
)

HEADER = """<!-- GENERATED by scripts/render_advisory.py — do not edit.
     Run `python scripts/render_advisory.py write` to regenerate. -->

# The rule registry — every rule you can cite by id

Rendered from `analitiq.contracts.shared.advisory.all_rules()` in the pinned
`analitiq-contract-models` package. Prose cites a rule by id (`ADV-ENDP-009`)
instead of restating it; an id that stops resolving fails the build, a restated
rule rots in silence.

Scope: the resources this plugin authors ({resources}). Pipeline, stream,
connection, and database-endpoint rules are excluded — they belong to other
tools, and database endpoints are generated at runtime by the connector's
`resource_discovery`, never authored here.

Each rule sits in one tier, and the tier tells you what happens when you break
it:

| Tier | What rejects a violation | What the message names |
|---|---|---|
| Relational | the validator, in-process | the rule id — quote it and stop |
| Structural | the published JSON Schema | the field; there is no id in the error |
| Waived | nothing in this repo | nothing — you find out later, or never |

{counts}
"""

RELATIONAL_INTRO = """
Constraints stock JSON Schema cannot express — set-equality, disjointness,
membership, cross-key uniqueness between sibling values. **The validator
enforces these**, so you do not need to memorize them, and a finding arrives
under `validator: "contract-model"` with the id already in the message.
"""

STRUCTURAL_INTRO = """
Carried by the model's own shape and published in the JSON Schema, so anyone
holding the schema rejects a violation — but the error names the field, never a
rule. These ids exist for prose: cite one instead of copying the shape into a
sentence that no longer moves when the model does.

**The Values column is read off the live model at render time.** It is the
current answer, not a promise, and it is the reason this file must be
regenerated rather than edited.
"""

WAIVER_INTRO = """
Normative, and nothing in this repo checks them. Each entry says which surface
would have to be read to catch a violation, and why that surface is out of
reach. Most `connector-package` rules are caught by registry CI or the CDK
conformance kit — after the connector is already written, which is the distance
this tier records. `authoring-choice` rules are caught by nobody: several
authorings all validate and only one is right.
"""


BORROWED_INTRO = """
Rules on documents this plugin does not author — a database endpoint the
connector's `resource_discovery` produces at run time, a stream that will
reference its endpoints. They are here because prose cites them to mark a
boundary, and an id you cannot look up marks nothing. **Do not author against
these**: they grade a document somebody else writes.
"""


def _load_rules():
    from analitiq.contracts.shared.advisory import all_rules

    return [r for r in all_rules() if r.resource in PLUGIN_RESOURCES]


def _load_borrowed():
    from analitiq.contracts.shared.advisory import all_rules

    by_id = {r.id: r for r in all_rules()}
    missing = [i for i in BORROWED_RULE_IDS if i not in by_id]
    if missing:
        raise RuntimeError(f"BORROWED_RULE_IDS names rules that do not exist: {missing}")
    return [by_id[i] for i in BORROWED_RULE_IDS]


def _model_index() -> dict:
    """Every contract model by class name, for reading live enum members."""
    from analitiq.contracts.shared.introspect import contract_classes

    return {cls.__name__: cls for cls in contract_classes()}


def _literal_members(annotation) -> list[str]:
    """Every string ``Literal`` member reachable in a field annotation."""
    import typing

    found: list[str] = []
    stack = [annotation]
    while stack:
        current = stack.pop()
        if typing.get_origin(current) is typing.Literal:
            found += [a for a in typing.get_args(current) if isinstance(a, str)]
        else:
            stack += list(typing.get_args(current))
    # Preserve declaration order without repeats; a set here would reorder the
    # rendered file on every Python run and make the drift check flap.
    return list(dict.fromkeys(found))


def _live_values(rule, models: dict) -> str:
    """The member list a structural rule points at, read from the model."""
    if rule.mechanism != "literal_enum":
        return "—"
    members: list[str] = []
    for target in rule.targets:
        model = models.get(target)
        if model is None:
            continue
        for expr in rule.fields:
            info = model.model_fields.get(expr.split("[]")[0].split(".")[0])
            if info is not None:
                members += _literal_members(info.annotation)
    members = list(dict.fromkeys(members))
    return ", ".join(f"`{m}`" for m in members) if members else "—"


def _shape(rule) -> str:
    """Where a structural rule's shape lives, as `Model.field (mechanism)`."""
    targets = ", ".join(rule.targets)
    fields = "/".join(rule.fields)
    where = f"`{targets}.{fields}`" if fields else f"`{targets}`"
    return f"{where} — {rule.mechanism}"


def _cell(text: str) -> str:
    """Markdown table cells cannot carry a bare pipe."""
    return text.replace("|", "\\|")


def _table(header: str, rows: list[str]) -> list[str]:
    columns = header.count("|") + 1
    return [
        f"| {header} |\n",
        "|" + "---|" * columns + "\n",
        *rows,
    ]


def _relational_section(rules: list) -> list[str]:
    out = [f"\n## Relational\n{RELATIONAL_INTRO}"]
    by_resource: dict[str, list] = {}
    for rule in rules:
        by_resource.setdefault(rule.resource, []).append(rule)
    for resource in [r for r in PLUGIN_RESOURCES if r in by_resource]:
        out.append(f"\n### {resource}\n\n")
        out += _table(
            "ID | Rule | Enforced on",
            [
                f"| {r.id} | {_cell(r.prose)} | "
                f"{', '.join(f'`{t}`' for t in r.targets) or '—'} |\n"
                for r in sorted(by_resource[resource], key=lambda r: r.id)
            ],
        )
    return out


def _structural_section(rules: list, models: dict) -> list[str]:
    return [
        f"\n## Structural\n{STRUCTURAL_INTRO}\n",
        *_table(
            "ID | Rule | Where the shape lives | Values",
            [
                f"| {r.id} | {_cell(r.prose)} | {_cell(_shape(r))} | "
                f"{_cell(_live_values(r, models))} |\n"
                for r in sorted(rules, key=lambda r: r.id)
            ],
        ),
    ]


def _waiver_section(rules: list) -> list[str]:
    return [
        f"\n## Waived\n{WAIVER_INTRO}\n",
        *_table(
            "ID | Rule | Governs | Why nothing here checks it",
            [
                f"| {r.id} | {_cell(r.prose)} | `{r.governs}` | {_cell(r.waiver)} |\n"
                for r in sorted(rules, key=lambda r: r.id)
            ],
        ),
    ]


def render() -> str:
    from analitiq.contracts.shared.advisory import (
        RELATIONAL_TIER,
        STRUCTURAL_TIER,
        TIERS,
        WAIVER_TIER,
    )

    rules = _load_rules()
    by_tier = {tier: [r for r in rules if r.tier == tier] for tier in TIERS}
    counts = " · ".join(f"**{len(by_tier[t])}** {t}" for t in TIERS)

    out = [
        HEADER.format(
            resources=", ".join(f"`{r}`" for r in PLUGIN_RESOURCES),
            counts=f"In scope: {counts}.\n",
        )
    ]
    if by_tier[RELATIONAL_TIER]:
        out += _relational_section(by_tier[RELATIONAL_TIER])
    if by_tier[STRUCTURAL_TIER]:
        out += _structural_section(by_tier[STRUCTURAL_TIER], _model_index())
    if by_tier[WAIVER_TIER]:
        out += _waiver_section(by_tier[WAIVER_TIER])

    borrowed = _load_borrowed()
    out += [
        f"\n## Borrowed — other documents' rules\n{BORROWED_INTRO}\n",
        *_table(
            "ID | Rule | Constrains",
            [
                f"| {r.id} | {_cell(r.prose)} | `{r.resource}` |\n"
                for r in sorted(borrowed, key=lambda r: r.id)
            ],
        ),
    ]

    return "".join(out)


def main(argv: list[str]) -> int:
    mode = argv[1] if len(argv) > 1 else "check"
    if mode not in ("write", "check"):
        print(f"usage: {argv[0]} [write|check]", file=sys.stderr)
        return 2

    rendered = render()

    if mode == "write":
        OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT_PATH.write_text(rendered, encoding="utf-8")
        print(f"wrote {OUTPUT_PATH.relative_to(REPO_ROOT)}")
        return 0

    if not OUTPUT_PATH.exists():
        print(f"{OUTPUT_PATH} is missing — run `render_advisory.py write`", file=sys.stderr)
        return 1
    if OUTPUT_PATH.read_text(encoding="utf-8") != rendered:
        print(
            f"{OUTPUT_PATH.relative_to(REPO_ROOT)} is stale — "
            "run `python scripts/render_advisory.py write`",
            file=sys.stderr,
        )
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
