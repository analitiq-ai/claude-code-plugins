#!/usr/bin/env python3
"""Render the rules the connector plugin authors against, tier by tier.

The rules are `rules/adv/*.yaml`, compiled into the pinned contract package and
read here through `all_rules()`. That registry is the source of truth; this
script only *renders* it, so agents have an offline-readable file to cite
instead of hand-restating rules in prose.

Tiers render as separate sections because an agent needs different things from
each — an `advisory` failure arrives with the id already in the message, a
`structural` one names only the field, and a `judgment` rule will never arrive
at all. The `Applied by` column says which of those a reader is looking at,
derived from the record rather than asserted here.

The structural table's member lists are read off the **live models** rather
than typed here: the point of that tier is to end the copy, so the renderer
must not become one.

The generated file is a **pinned copy**, not a second source: `tests/connector_builder`
regenerates it and fails when it is stale, so a contract change surfaces as a red
build rather than silent prose drift.

Usage:
    render_advisory.py write    # regenerate the markdown file in place
    render_advisory.py check    # exit 1 if the file is stale (CI)
"""

from __future__ import annotations

import os
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent

# This repo is the contract's SOURCE, so bootstrap the same way render_schemas.py
# does rather than relying on an installed wheel — requirements-dev.txt
# deliberately does not install one. Keeps the script runnable standalone (CI
# calls it directly, outside pytest and its conftest).
sys.path.insert(0, str(REPO_ROOT / "packages" / "contract-models" / "src"))
# `analitiq.contracts.shared.common` reads os.environ["DOMAIN"] at import and
# raises KeyError without it.
os.environ.setdefault("DOMAIN", "analitiq.ai")
OUTPUT_PATH = (
    REPO_ROOT / "plugins" / "analitiq-connector-builder" / "skills" / "connector-builder" / "references" / "advisory-rules.md"
)

# Which plugin this file belongs to. A rule reaches it when its `owners` name
# that plugin — the record's own answer to "who applies this", so a rule an
# agent here has to know is rendered here because the record says so, and
# nothing downstream has to check that a citation resolved.
#
# `scope` deliberately does NOT decide this. Scope is which artifact a rule
# grades; ownership is who has to know it, and the two differ exactly where it
# matters: this plugin never authors a database endpoint, but its
# `resource_discovery` produces one, so `ADV-DBEP-*` binds an author here.
PLUGIN_OWNER = "connector-plugin"

HEADER = """<!-- GENERATED by scripts/render_advisory.py — do not edit.
     Run `python scripts/render_advisory.py write` to regenerate. -->

# The rule registry — every rule you can cite by id

Rendered from the rule registry (`rules/adv/*.yaml`) as the pinned
`analitiq-contract-models` package ships it. Prose cites a rule by id
(`ADV-ENDP-009`) instead of restating it; an id that stops resolving fails the
build, a restated rule rots in silence.

Scope: every rule this plugin owns. A rule is here because its record names
`{owner}` as an owner, so any id you meet in this plugin's prose is a row
below — including rules on documents authored elsewhere that an author here
still has to satisfy, like the endpoints `resource_discovery` produces.

Every rule carries three independent facts. **Tier** is what kind of rule it
is; **Severity** is what a violation costs; **Applied by** is what rejects one,
and `—` there means nothing here does — you find out later, or never.

{counts}
"""

TIER_INTRO = {
    "structural": """
One artifact has this shape. Usually a `Literal`, a pattern, a bound or a
closed object rendered into the published JSON Schema — so anyone holding the
schema rejects a violation, but the error names the field and never a rule.
These ids exist for prose: cite one instead of copying the shape into a
sentence that stops moving when the model does.

**The Values column is read off the live model at render time.** It is the
current answer, not a promise, and it is why this file is regenerated rather
than edited.
""",
    "advisory": """
Fields *within* one document that must agree — set-equality, disjointness,
membership, cross-key uniqueness. Stock JSON Schema cannot state these, so the
validator enforces them in-process and the finding arrives under
`validator: "contract-model"` with the id already in the message. You do not
need to memorize them; you need to recognise the id.
""",
    "referential": """
This artifact must agree with **another** one — a `connector_id` against the
directory it ships in, a declared capability against the hook implementing it,
an endpoint against the connector declaring it. Most are applied by nothing
here: a single-document validation run has only one of the two artifacts in
hand, so the disagreement surfaces at connect or run time.
""",
    "procedural": """
Do it this way, or in this order. What is regenerated after what, what is never
hand-edited, what the engine owns and is therefore never authored. Violating
one usually produces a document that validates and then behaves unexpectedly.
""",
    "judgment": """
Several authorings all validate and one is right. No validator can flag a
legal-but-wrong choice, so these are the rules an agent gets wrong while
passing every check — read the prose that cites them, not just the statement.
""",
}

def _load_rules():
    from analitiq.contracts.shared.advisory import all_rules

    return [r for r in all_rules() if PLUGIN_OWNER in r.owners]


def rendered_ids() -> set[str]:
    """Every id this file makes readable, as the renderer knows it.

    The renderer is the authority on what it rendered, so a consumer asks it
    rather than searching its output for row-shaped text. That search is what a
    guard here used to do, and it could only ever find the malformed rows
    somebody had already thought of.
    """
    return {r.id for r in _load_rules()}


def _model_index() -> dict:
    """Every contract model by class name, for reading live enum members."""
    from analitiq.contracts.shared.introspect import contract_classes

    return {cls.__name__: cls for cls in contract_classes()}


def _literal_members(annotation) -> list[str]:
    """Every string ``Literal`` member reachable in a field annotation."""
    import typing

    found: list[str] = []
    stack = [annotation]
    while stack:
        current = stack.pop()
        if typing.get_origin(current) is typing.Literal:
            found += [a for a in typing.get_args(current) if isinstance(a, str)]
        else:
            stack += list(typing.get_args(current))
    # Preserve declaration order without repeats; a set here would reorder the
    # rendered file on every Python run and make the drift check flap.
    return list(dict.fromkeys(found))


def _live_values(rule, models: dict) -> str:
    """The member list a structural rule points at, read from the model."""
    if rule.mechanism != "literal_enum":
        return "—"
    members: list[str] = []
    for target in rule.targets:
        model = models.get(target)
        if model is None:
            continue
        for expr in rule.fields:
            info = model.model_fields.get(expr.split("[]")[0].split(".")[0])
            if info is not None:
                members += _literal_members(info.annotation)
    members = list(dict.fromkeys(members))
    return ", ".join(f"`{m}`" for m in members) if members else "—"


def _applied_by(rule) -> str:
    """What rejects a violation, in the fewest words that stay true.

    Read off `validator`, never asserted: the registry's own relational checks
    are the validator itself, a model validator or a field is that symbol, and
    an agent rule is the document an agent loads. Nothing set means nothing
    applies it, which is the answer a reader most needs.
    """
    if not rule.validator:
        return "—"
    if rule.validator.endswith(".md"):
        return f"`{rule.validator}`"
    symbol = rule.validator_symbol
    return "the validator" if rule.engine_dispatched else f"`{symbol}`"


def _cell(text: str) -> str:
    """Flatten a value into something a markdown table cell can hold.

    A bare `|` ends the cell. A newline ends the *row* — and every `statement`
    is authored as a YAML folded scalar, so each one arrives with a trailing
    newline. `split()` on arbitrary whitespace also collapses runs, which is
    what the fold already did to the scalar's interior, so a record reflowed to
    a different line width renders identically.
    """
    return " ".join(text.replace("|", "\\|").split())


def _row(cells: list[str]) -> str:
    """One table row, or an exception. Never a row that renders as prose.

    A markdown row is one line: nothing continues it, so a cell carrying a
    newline does not wrap, it ends the row early and orphans every later column
    onto a line that renders as body text. The rule stays in the file and stops
    being readable, which is worse than its absence — an agent following a
    citation finds the id and not the rule.

    So the invariant is enforced where the row is built, not looked for
    afterwards in the output. `_cell` is the only sanctioned way to prepare a
    value; this catches the caller who forgets it, and names the offending text
    instead of leaving a malformed file for a test to characterise.
    """
    for cell in cells:
        if "\n" in cell:
            raise ValueError(
                f"table cell would split its row across lines: {cell!r}. "
                "Pass it through `_cell` first."
            )
    return "| " + " | ".join(cells) + " |\n"


def _table(header: list[str], rows: list[str]) -> list[str]:
    return [_row(header), "|" + "---|" * len(header) + "\n", *rows]


def _tier_section(tier: str, rules: list, models: dict) -> list[str]:
    structural = tier == "structural"
    header = ["ID", "Rule", "Grades", "Severity", "Applied by"]
    if structural:
        header.append("Values")
    rows = []
    for r in sorted(rules, key=lambda r: r.id):
        cells = [
            r.id,
            _cell(r.statement),
            f"`{r.scope}`",
            r.severity,
            _cell(_applied_by(r)),
        ]
        if structural:
            cells.append(_cell(_live_values(r, models)))
        rows.append(_row(cells))
    return [f"\n## {tier.capitalize()}\n{TIER_INTRO[tier]}\n", *_table(header, rows)]


def render() -> str:
    from analitiq.contracts.shared.rule_record import TIERS

    rules = _load_rules()
    models = _model_index()
    by_tier = {tier: [r for r in rules if r.tier == tier] for tier in TIERS}
    counts = " · ".join(f"**{len(by_tier[t])}** {t}" for t in TIERS if by_tier[t])

    out = [HEADER.format(owner=PLUGIN_OWNER, counts=f"Owned here: {counts}.\n")]
    for tier in TIERS:
        if by_tier[tier]:
            out += _tier_section(tier, by_tier[tier], models)
    return "".join(out)


def main(argv: list[str]) -> int:
    mode = argv[1] if len(argv) > 1 else "check"
    if mode not in ("write", "check"):
        print(f"usage: {argv[0]} [write|check]", file=sys.stderr)
        return 2

    rendered = render()

    if mode == "write":
        OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT_PATH.write_text(rendered, encoding="utf-8")
        print(f"wrote {OUTPUT_PATH.relative_to(REPO_ROOT)}")
        return 0

    if not OUTPUT_PATH.exists():
        print(f"{OUTPUT_PATH} is missing — run `render_advisory.py write`", file=sys.stderr)
        return 1
    if OUTPUT_PATH.read_text(encoding="utf-8") != rendered:
        print(
            f"{OUTPUT_PATH.relative_to(REPO_ROOT)} is stale — "
            "run `python scripts/render_advisory.py write`",
            file=sys.stderr,
        )
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
