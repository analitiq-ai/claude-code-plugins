"""Prove the contracts-version stamp is current, honest, and wired.

`schemas/contracts-version.json` is the published tree's provenance: the
`analitiq-contract-models` release the tree renders from, generated by
`scripts/render_schemas.py contracts-version` from the package's own
pyproject and covered by the full render `check`. CI's check only exercises
the clean path — these tests inject the failure states (stale stamp, missing
stamp, versionless pyproject) and pin the cross-file facts no import can
carry: `scripts/check_contracts_version_pin.py` cannot import the renderer
(the guard job installs nothing and the renderer imports pydantic), so the
stamp's key, the paths, the serving host, and the sentinel's basename are
stated in the guard as copies of renderer-owned values and pinned equal here.
"""
from __future__ import annotations

import sys
from importlib.util import module_from_spec, spec_from_file_location
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO_ROOT / "scripts"))
sys.path.insert(0, str(REPO_ROOT / "tests" / "connector_builder"))

from _pins import require_contract_models  # noqa: E402

require_contract_models("analitiq.contracts", "render_schemas")

import render_schemas  # noqa: E402


@pytest.fixture(scope="module")
def guard():
    spec = spec_from_file_location(
        "check_contracts_version_pin",
        REPO_ROOT / "scripts" / "check_contracts_version_pin.py",
    )
    module = module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def test_committed_stamp_is_current():
    ok, msg = render_schemas.check_contracts_version()
    assert ok, msg


def test_stamp_states_the_pyproject_version_and_the_tree_digest():
    doc = render_schemas.build_contracts_version_doc()
    assert (
        doc[render_schemas.CONTRACTS_VERSION_KEY]
        == render_schemas.contract_models_version()
    )
    assert doc["tree_sha256"] == render_schemas.schemas_tree_digest()


def test_tree_digest_moves_with_the_tree_and_ignores_the_stamp(
    monkeypatch, tmp_path
):
    """The digest is what makes the stamp change on every render — without
    that, a publish that failed to land a re-render is undetectable from the
    stamp whenever the package version did not move."""
    tree = tmp_path / "schemas"
    (tree / "connector").mkdir(parents=True)
    doc = tree / "connector" / "1.0.0.json"
    doc.write_text("{}")
    stamp = tree / "contracts-version.json"
    monkeypatch.setattr(render_schemas, "SCHEMAS_ROOT", tree)
    monkeypatch.setattr(render_schemas, "CONTRACTS_VERSION_PATH", stamp)

    baseline = render_schemas.schemas_tree_digest()
    stamp.write_text('{"anything": "at all"}')
    assert render_schemas.schemas_tree_digest() == baseline, (
        "the stamp must not feed its own digest"
    )
    doc.write_text('{"changed": true}')
    assert render_schemas.schemas_tree_digest() != baseline


def test_full_check_gates_the_stamp(monkeypatch, tmp_path):
    """schemas-publish.yml's verify step runs only `render_schemas.py check`
    (plus one canonical-types pytest module), so the stamp's only content
    gate on the publish path is the full check reaching
    check_contracts_version — dropping it from cmd_check must fail here, not
    silently un-gate the publish."""
    stale = tmp_path / "contracts-version.json"
    stale.write_text('{"analitiq-contract-models": "0.0.0"}\n')
    monkeypatch.setattr(render_schemas, "CONTRACTS_VERSION_PATH", stale)
    assert render_schemas.main(["check"]) == 1


def test_renderer_and_guard_agree_on_key_paths_and_host(guard):
    """The guard reads what the renderer writes, without importing it.

    The fact key, the file paths, the serving host (carried for every guard
    by `scripts/_guard_lib.py`), and the sentinel's basename therefore exist
    guard-side as copies of renderer-owned (or contract-owned) values; these
    pins are what make each copy one value
    (`.claude/rules/no-drift-surfaces.md`).
    """
    assert guard.CONTRACTS_VERSION_KEY == render_schemas.CONTRACTS_VERSION_KEY
    assert guard.COMMITTED_PATH == render_schemas.CONTRACTS_VERSION_PATH
    assert guard.PYPROJECT_PATH == render_schemas.CONTRACT_MODELS_PYPROJECT
    # The host is owned by analitiq.contracts.shared.common.SCHEMA_BASE_URL,
    # re-exported by the renderer as CANONICAL_BASE.
    assert guard.BASE_URL == render_schemas.CANONICAL_BASE
    assert guard.PUBLISHED_URL == (
        f"{render_schemas.CANONICAL_BASE}/{render_schemas.CONTRACTS_VERSION_PATH.name}"
    )
    assert guard.SENTINEL_URL == (
        f"{render_schemas.CANONICAL_BASE}/{render_schemas.CANONICAL_TYPES_PATH.name}"
    )


def test_versionless_pyproject_fails_loudly(monkeypatch, tmp_path):
    """A pyproject the parse cannot read a version from must refuse to render
    — a silently empty or wrong stamp would publish a false provenance fact."""
    broken = tmp_path / "pyproject.toml"
    broken.write_text('[project]\nname = "analitiq-contract-models"\n')
    monkeypatch.setattr(render_schemas, "CONTRACT_MODELS_PYPROJECT", broken)
    with pytest.raises(RuntimeError):
        render_schemas.contract_models_version()
    ok, _ = render_schemas.check_contracts_version()
    assert not ok


def test_stale_stamp_names_the_fix(monkeypatch, tmp_path):
    stale = tmp_path / "contracts-version.json"
    stale.write_text('{"analitiq-contract-models": "0.0.0"}\n')
    monkeypatch.setattr(render_schemas, "CONTRACTS_VERSION_PATH", stale)
    ok, msg = render_schemas.check_contracts_version()
    assert not ok and "contracts-version`" in msg


def test_missing_stamp_names_the_fix(monkeypatch, tmp_path):
    monkeypatch.setattr(
        render_schemas, "CONTRACTS_VERSION_PATH", tmp_path / "absent.json"
    )
    ok, msg = render_schemas.check_contracts_version()
    assert not ok and "contracts-version`" in msg
